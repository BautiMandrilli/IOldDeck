const data = JSON.parse(await readFile(path.join(source, 'data/simple-icons.json'), 'utf8'));
const pkg = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
const out = [];
for (const [slug, name, category, url, bg, fg] of APPS) {
  const meta = data.find(item => item.slug === slug);
  if (!meta) { console.warn('Skipped (not in simple-icons):', slug); continue; }
  const svg = await readFile(path.join(source, 'icons', slug + '.svg'), 'utf8');
  const d = /<path d="([^"]+)"/.exec(svg)[1];
  out.push({ slug, name, category, url, bg: bg || '#' + meta.hex, fg: fg || '#ffffff', path: d });
}
